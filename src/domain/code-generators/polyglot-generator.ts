/**
 * Polyglot Scientific Code Generator (Python, R, LaTeX PGFPlots)
 * Generates deterministic, 1-click reproducible scripts from canvas parameters.
 */

import { PolyglotCodeExport } from '../types';

export function generatePolyglotScripts(
  a: number,
  b: number,
  c: number,
  xMin: number = -10,
  xMax: number = 10
): PolyglotCodeExport {
  // 1. Python NumPy + Matplotlib
  const pythonScript = `# -*- coding: utf-8 -*-
"""
Math Lab Deterministic Reproducibility Script
Model: Kuadratik f(x) = ${a}x^2 + ${b}x + ${c}
Generated by Math Lab (https://mymathlab.id)
"""
import numpy as np
import matplotlib.pyplot as plt

# Parameter Model
a = ${a}
b = ${b}
c = ${c}

# Domain & Fungsi
x = np.linspace(${xMin}, ${xMax}, 400)
y = a * x**2 + b * x + c

# Titik Karakteristik
h = -b / (2 * a) if a != 0 else 0
k = a * h**2 + b * h + c if a != 0 else c
d = b**2 - 4 * a * c

plt.figure(figsize=(8, 6), dpi=150)
plt.plot(x, y, label=f"f(x) = {a}x² + {b}x + {c}", color="#4338ca", linewidth=2.5)

# Gambar Titik Puncak
if a != 0:
    plt.scatter([h], [k], color="#dc2626", s=60, zorder=5, label=f"Puncak ({h:.2f}, {k:.2f})")
    plt.axvline(x=h, color="#9ca3af", linestyle="--", linewidth=1, label=f"Sumbu Simetri x={h:.2f}")

# Garis Sumbu Koordinat
plt.axhline(0, color="#1f2937", linewidth=1.2)
plt.axvline(0, color="#1f2937", linewidth=1.2)
plt.grid(True, linestyle=":", alpha=0.6)

plt.title("Visualisasi Fungsi Kuadrat - Math Lab", fontsize=14, fontweight="bold", pad=12)
plt.xlabel("Sumbu x", fontsize=11)
plt.ylabel("f(x)", fontsize=11)
plt.legend(frameon=True, loc="best")
plt.tight_layout()
plt.show()
`;

  // 2. R ggplot2
  const rScript = `#' Math Lab Deterministic Reproducibility Script
#' Model: Kuadratik f(x) = ${a}x^2 + ${b}x + ${c}
#' Generated by Math Lab (https://mymathlab.id)

library(ggplot2)

# Parameter Model
a <- ${a}
b <- ${b}
c <- ${c}

# Data Frame Titik
df <- data.frame(x = seq(${xMin}, ${xMax}, length.out = 400))
df$y <- a * df$x^2 + b * df$x + c

# Titik Puncak
h <- ifelse(a != 0, -b / (2 * a), 0)
k <- ifelse(a != 0, a * h^2 + b * h + c, c)

ggplot(df, aes(x = x, y = y)) +
  geom_line(color = "#4338ca", size = 1.2) +
  geom_hline(yintercept = 0, color = "#1f2937", size = 0.6) +
  geom_vline(xintercept = 0, color = "#1f2937", size = 0.6) +
  geom_point(aes(x = h, y = k), color = "#dc2626", size = 3) +
  geom_vline(xintercept = h, linetype = "dashed", color = "#9ca3af") +
  theme_minimal(base_family = "sans") +
  labs(
    title = paste0("Model Kuadrat: f(x) = ", a, "x² + ", b, "x + ", c),
    subtitle = paste0("Titik Puncak: (", round(h, 2), ", ", round(k, 2), ") | D = ", round(b^2 - 4*a*c, 2)),
    x = "Sumbu x",
    y = "f(x)"
  )
`;

  // 3. LaTeX PGFPlots / TikZ
  const latexScript = `% Math Lab PGFPlots Export
% Siap dikompilasi di Overleaf / LaTeX TeXLive
\\documentclass[tikz,border=5mm]{standalone}
\\usepackage{pgfplots}
\\pgfplotsset{compat=1.18}

\\begin{document}
\\begin{tikzpicture}
  \\begin{axis}[
    title={Model: $f(x) = ${a}x^2 + ${b}x + ${c}$},
    axis lines=middle,
    grid=major,
    grid style={dashed, gray!30},
    xlabel={$x$},
    ylabel={$f(x)$},
    xmin=${xMin}, xmax=${xMax},
    ymin=${xMin}, ymax=${xMax},
    width=10cm, height=8cm,
    samples=100
  ]
    % Kurva Kuadrat
    \\addplot[domain=${xMin}:${xMax}, thick, color=blue!70!black] {${a}*x^2 + ${b}*x + ${c}};
    
    % Titik Puncak
    \\node[label={above:Puncak}] at (axis cs:${a !== 0 ? (-b / (2 * a)).toFixed(2) : 0}, ${a !== 0 ? (a * Math.pow(-b / (2 * a), 2) + b * (-b / (2 * a)) + c).toFixed(2) : c}) {};
    \\fill[red] (axis cs:${a !== 0 ? (-b / (2 * a)).toFixed(2) : 0}, ${a !== 0 ? (a * Math.pow(-b / (2 * a), 2) + b * (-b / (2 * a)) + c).toFixed(2) : c}) circle (2pt);
  \\end{axis}
\\end{tikzpicture}
\\end{document}
`;

  return {
    pythonNumPyMatplotlib: pythonScript,
    rGgplot2: rScript,
    latexPgfplotsTikz: latexScript
  };
}
